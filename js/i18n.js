export const lang = document.documentElement.lang === "ar" ? "ar" : "en";
export const isRTL = lang === "ar";

export function t(key, vars = {}) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

export function setLang(next) {
  try { localStorage.setItem("bloom-lang", next); } catch {}
  location.reload();
}

export function formatPrice(sar) {
  const n = Math.round(sar).toLocaleString("en-US");
  return lang === "ar" ? `${n} ر.س` : `SAR ${n}`;
}

export function categoryName(slug) {
  return t(`cat.${slug}`);
}

export function countLabel(n, oneKey, manyKey) {
  return n === 1 ? t(oneKey) : t(manyKey, { n });
}

